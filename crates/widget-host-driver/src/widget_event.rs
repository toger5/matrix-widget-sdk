//! Widget state events: which state events of a room are widgets, and what a client loads for them.
//!
//! MSC4411 defines `m.widget` (unstable `org.matrix.msc4411.widget`); `uses_widget_api` comes from
//! MSC4412. `im.vector.modular.widgets` is the event of today's clients (Element): its widgets speak
//! the legacy widget API, so they run inside the compat wrapper (`packages/widget-compat-wrapper`),
//! which translates. This is host-side vocabulary: widgets never see the event, which is why it
//! lives here and not in `widget-actions`.
//!
//! Two steps, so that a client can list widgets without loading them:
//!
//! 1. [`WidgetDefinition::parse`]: a state event becomes the widget it describes, or the reason it
//!    describes none (another event type, a removed widget).
//! 2. [`WidgetDefinition::embed`]: the widget becomes the URL of its iframe (webview), or the reason
//!    it must not be loaded ([`embed_url_problem`](crate::embed_url_problem)). A legacy widget is loaded through the compat
//!    wrapper, with its URL template and data as query parameters of the wrapper's URL.

use serde_json::Value;
use widget_actions::JsonValue;

use crate::widget_url::{checked_embed_url, checked_widget_url};

/// Stable event type of the widget state event (MSC4411).
pub const WIDGET_EVENT_TYPE: &str = "m.widget";
/// Unstable event type of the widget state event (MSC4411).
pub const WIDGET_EVENT_TYPE_UNSTABLE: &str = "org.matrix.msc4411.widget";
/// Legacy event type of matrix-widget-api clients (Element); its widgets run in the compat wrapper.
pub const WIDGET_EVENT_TYPE_LEGACY: &str = "im.vector.modular.widgets";
/// Every state event type that describes a widget, the MSC4411 ones first.
pub const WIDGET_EVENT_TYPES: [&str; 3] = [WIDGET_EVENT_TYPE, WIDGET_EVENT_TYPE_UNSTABLE, WIDGET_EVENT_TYPE_LEGACY];

/// The query parameters of the compat wrapper's URL that [`WidgetDefinition::embed`] sets.
const WRAPPER_PARAMETERS: [&str; 4] =
    ["legacy_widget_url", "legacy_widget_id", "legacy_wait_for_iframe_load", "legacy_widget_data"];

/// A widget as its state event describes it: what a client lists. Load it only through
/// [`embed`](Self::embed), which checks the URL.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "uniffi", derive(uniffi::Record))]
pub struct WidgetDefinition {
    /// One of [`WIDGET_EVENT_TYPES`].
    pub event_type: String,
    /// The state key: the widget id (MSC4411: opaque, generated by the client that added it).
    pub widget_id: String,
    /// `content.name`, or the widget id when the name is empty (or, for a legacy widget, missing).
    pub name: String,
    /// `content.url` as it is, not checked. For a legacy widget a URL template (`$matrix_user_id`
    /// & co.), which the compat wrapper fills in.
    pub url: String,
    /// `content.avatar_url`: an `mxc://` URI (MSC2765).
    pub avatar_url: Option<String>,
    /// `content.uses_widget_api` (MSC4412) is `true`: set up the widget API and wait for
    /// `notify_ready` before showing the widget. Always `false` for a legacy widget; its
    /// [`WidgetEmbed`] says `true`, since the compat wrapper speaks the API.
    pub uses_widget_api: bool,
    /// The fields of `im.vector.modular.widgets` the compat wrapper needs; `None` for an MSC4411
    /// widget.
    pub legacy: Option<LegacyWidget>,
}

/// What only a legacy widget (`im.vector.modular.widgets`) has.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "uniffi", derive(uniffi::Record))]
pub struct LegacyWidget {
    /// `content.type`: `m.custom`, `m.jitsi`, `m.call`, … (Element lists a widget only with one).
    pub widget_type: Option<String>,
    /// `content.waitForIframeLoad`, `true` unless it is `false`: when the legacy widget's
    /// capability round starts (see the compat wrapper's README).
    pub wait_for_iframe_load: bool,
    /// `content.data` when it is an object with at least one key: the values of its extra `$key`
    /// template variables.
    pub data: Option<JsonValue>,
}

/// What a client puts into the iframe (webview) of a widget.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "uniffi", derive(uniffi::Record))]
pub struct WidgetEmbed {
    /// The URL to load: the widget's own as the URL check parsed and serialised it (so the iframe
    /// loads exactly what was checked), or for a legacy widget the compat wrapper with the widget
    /// in its query. Always an absolute `http:` or `https:` URL.
    pub url: String,
    /// Set up the widget API and wait for `notify_ready` before showing the widget.
    pub uses_widget_api: bool,
}

/// Why a state event is no widget, or why a widget must not be loaded.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[cfg_attr(feature = "uniffi", derive(uniffi::Error))]
pub enum WidgetEventError {
    /// The event type is none of [`WIDGET_EVENT_TYPES`].
    #[error("{event_type} is not a widget state event type")]
    NotAWidgetType { event_type: String },
    /// The content describes no widget: the widget was removed (clients set the content to `{}`),
    /// or the content does not match the event's schema. Not to be listed.
    #[error("removed widget: {reason}")]
    Removed { reason: String },
    /// The widget must not be loaded; `reason` names the problem (the URL check).
    #[error("{reason}")]
    Refused { reason: String },
}

impl WidgetDefinition {
    /// The widget a state event describes.
    ///
    /// MSC4411 widgets need a string `url` and a string `name`; legacy widgets a string `url`
    /// (removing a widget leaves an event without one). Fields of the wrong type are ignored.
    pub fn parse(event_type: &str, state_key: &str, content: &Value) -> Result<Self, WidgetEventError> {
        let legacy = match event_type {
            WIDGET_EVENT_TYPE | WIDGET_EVENT_TYPE_UNSTABLE => false,
            WIDGET_EVENT_TYPE_LEGACY => true,
            _ => return Err(WidgetEventError::NotAWidgetType { event_type: event_type.to_owned() }),
        };
        let string = |key: &str| content.get(key).and_then(Value::as_str);
        let removed = |field: &str| WidgetEventError::Removed { reason: format!("the content has no {field}") };
        let url = string("url").ok_or_else(|| removed("url"))?;
        let name = string("name");
        // MSC4411: an `m.widget` whose content lacks a string `name` or `url` is a removed widget.
        if !legacy && name.is_none() {
            return Err(removed("name"));
        }
        Ok(Self {
            event_type: event_type.to_owned(),
            widget_id: state_key.to_owned(),
            name: name.filter(|name| !name.is_empty()).unwrap_or(state_key).to_owned(),
            url: url.to_owned(),
            avatar_url: string("avatar_url").map(str::to_owned),
            uses_widget_api: !legacy && content.get("uses_widget_api") == Some(&Value::Bool(true)),
            legacy: legacy.then(|| LegacyWidget {
                widget_type: string("type").map(str::to_owned),
                wait_for_iframe_load: content.get("waitForIframeLoad") != Some(&Value::Bool(false)),
                data: content
                    .get("data")
                    .filter(|data| data.as_object().is_some_and(|object| !object.is_empty()))
                    .map(|data| JsonValue(data.clone())),
            }),
        })
    }

    /// What the iframe (webview) of this widget loads, after the URL check ([`embed_url_problem`](crate::embed_url_problem):
    /// [`widget_url_problem`](crate::widget_url_problem), and no page of the compat wrapper at
    /// `wrapper_url`, for widgets of both kinds).
    ///
    /// An MSC4411 widget loads its own URL, serialised as the check parsed it (`  HTTPS://Bücher.example/a b`
    /// loads `https://xn--bcher-kva.example/a%20b`): no other URL parser gets to read the event's
    /// string differently. A legacy widget loads the compat wrapper at
    /// `wrapper_url` (checked like a widget URL, so `None` refuses every legacy widget) with
    /// `legacy_widget_url` (the untemplated URL), `legacy_widget_id`, `legacy_wait_for_iframe_load`
    /// and, with data, `legacy_widget_data` (JSON) added to its query; they replace any the wrapper
    /// URL already has (the wrapper reads the first of a parameter, so one in the wrapper URL would
    /// load another widget than this one). The host never fills in the template: the wrapper asks
    /// for the values through `get_matrix_context` / `get_client_context`. `allow_http`: also
    /// `http:` URLs (MSC4411: in developer tools).
    pub fn embed(&self, wrapper_url: Option<&str>, allow_http: bool) -> Result<WidgetEmbed, WidgetEventError> {
        let refused = |reason: String| WidgetEventError::Refused { reason };
        let checked = checked_embed_url(&self.url, wrapper_url, allow_http).map_err(refused)?;
        let Some(legacy) = &self.legacy else {
            return Ok(WidgetEmbed { url: checked.into(), uses_widget_api: self.uses_widget_api });
        };
        let wrapper_url = wrapper_url.ok_or_else(|| refused("a legacy widget needs the compat wrapper".to_owned()))?;
        let mut url = checked_widget_url(wrapper_url, allow_http)
            .map_err(|problem| refused(format!("compat wrapper: {problem}")))?;
        if url.query_pairs().any(|(key, _)| WRAPPER_PARAMETERS.contains(&key.as_ref())) {
            let kept: Vec<(String, String)> = url
                .query_pairs()
                .filter(|(key, _)| !WRAPPER_PARAMETERS.contains(&key.as_ref()))
                .map(|(key, value)| (key.into_owned(), value.into_owned()))
                .collect();
            url.query_pairs_mut().clear().extend_pairs(kept);
        }
        {
            let mut query = url.query_pairs_mut();
            query
                .append_pair("legacy_widget_url", &self.url)
                .append_pair("legacy_widget_id", &self.widget_id)
                .append_pair("legacy_wait_for_iframe_load", if legacy.wait_for_iframe_load { "true" } else { "false" });
            if let Some(data) = &legacy.data {
                query.append_pair("legacy_widget_data", &data.to_string());
            }
        }
        Ok(WidgetEmbed { url: url.into(), uses_widget_api: true })
    }
}

/// [`WidgetDefinition::parse`] for foreign code: `content` is the event content as JSON.
#[cfg_attr(feature = "uniffi", uniffi::export)]
pub fn parse_widget_state_event(
    event_type: String,
    state_key: String,
    content: JsonValue,
) -> Result<WidgetDefinition, WidgetEventError> {
    WidgetDefinition::parse(&event_type, &state_key, &content)
}

/// [`WidgetDefinition::embed`] for foreign code.
#[cfg_attr(feature = "uniffi", uniffi::export)]
pub fn embed_widget(
    widget: WidgetDefinition,
    wrapper_url: Option<String>,
    allow_http: bool,
) -> Result<WidgetEmbed, WidgetEventError> {
    widget.embed(wrapper_url.as_deref(), allow_http)
}

/// [`WIDGET_EVENT_TYPES`] for foreign code: the state event types to read for a room's widgets.
#[cfg_attr(feature = "uniffi", uniffi::export)]
pub fn widget_event_types() -> Vec<String> {
    WIDGET_EVENT_TYPES.iter().map(|t| (*t).to_owned()).collect()
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use serde_json::json;
    use url::Url;

    use super::*;
    use crate::widget_url_problem;

    const WRAPPER: &str = "http://localhost:5173/widget_compatibility_wrapper/";

    fn parse(event_type: &str, content: Value) -> Result<WidgetDefinition, WidgetEventError> {
        WidgetDefinition::parse(event_type, "w", &content)
    }

    fn new_widget(url: &str) -> WidgetDefinition {
        parse("m.widget", json!({ "name": "W", "url": url, "uses_widget_api": true })).unwrap()
    }

    fn legacy_widget(url: &str) -> WidgetDefinition {
        parse("im.vector.modular.widgets", json!({ "type": "m.custom", "name": "W", "url": url })).unwrap()
    }

    /// The query of a URL, decoded.
    fn query(url: &str) -> Vec<(String, String)> {
        Url::parse(url).unwrap().query_pairs().map(|(k, v)| (k.into_owned(), v.into_owned())).collect()
    }

    fn table(part: &str) -> BTreeMap<String, String> {
        let table: Value = serde_json::from_str(include_str!("../tests/widget_urls.json")).unwrap();
        serde_json::from_value(table[part].clone()).unwrap()
    }

    #[test]
    fn msc4411_widgets() {
        for event_type in ["m.widget", "org.matrix.msc4411.widget"] {
            let widget = parse(
                event_type,
                json!({ "name": "Notes", "url": "https://w.example/notes", "avatar_url": "mxc://a/b", "uses_widget_api": true }),
            )
            .unwrap();
            assert_eq!(
                widget,
                WidgetDefinition {
                    event_type: event_type.to_owned(),
                    widget_id: "w".to_owned(),
                    name: "Notes".to_owned(),
                    url: "https://w.example/notes".to_owned(),
                    avatar_url: Some("mxc://a/b".to_owned()),
                    uses_widget_api: true,
                    legacy: None,
                }
            );
        }
        // Only `true` sets up the widget API.
        for value in [json!(false), json!("true"), json!(1), Value::Null] {
            let widget = parse("m.widget", json!({ "name": "n", "url": "https://x/", "uses_widget_api": value }));
            assert!(!widget.unwrap().uses_widget_api);
        }
        assert!(!parse("m.widget", json!({ "name": "n", "url": "https://x/" })).unwrap().uses_widget_api);
        // Fields of the wrong type are ignored; an empty name shows the widget id.
        let odd = parse("m.widget", json!({ "name": "", "url": "https://x/", "avatar_url": 3 })).unwrap();
        assert_eq!((odd.name.as_str(), odd.avatar_url), ("w", None));
    }

    #[test]
    fn legacy_widgets() {
        let widget = parse(
            "im.vector.modular.widgets",
            json!({
                "type": "m.custom", "name": "Notes", "url": "https://w.example/?u=$matrix_user_id",
                "waitForIframeLoad": false, "data": { "title": "Notes & more" }, "creatorUserId": "@a:b",
                "uses_widget_api": true,
            }),
        )
        .unwrap();
        assert_eq!(widget.url, "https://w.example/?u=$matrix_user_id");
        assert!(!widget.uses_widget_api, "a legacy widget speaks the legacy API");
        assert_eq!(
            widget.legacy,
            Some(LegacyWidget {
                widget_type: Some("m.custom".to_owned()),
                wait_for_iframe_load: false,
                data: Some(JsonValue(json!({ "title": "Notes & more" }))),
            })
        );
        // Defaults: no name shows the widget id, waitForIframeLoad is true unless false, data only as a non-empty object.
        for data in [json!({}), json!("text"), json!([1]), Value::Null] {
            let plain = parse(
                "im.vector.modular.widgets",
                json!({ "url": "https://x/", "waitForIframeLoad": "false", "data": data }),
            )
            .unwrap();
            assert_eq!(plain.name, "w");
            assert_eq!(plain.legacy, Some(LegacyWidget { widget_type: None, wait_for_iframe_load: true, data: None }));
        }
    }

    #[test]
    fn removed_widgets_and_other_events() {
        let removed = |field: &str| -> Result<WidgetDefinition, WidgetEventError> {
            Err(WidgetEventError::Removed { reason: format!("the content has no {field}") })
        };
        for event_type in WIDGET_EVENT_TYPES {
            assert_eq!(parse(event_type, json!({})), removed("url"));
            assert_eq!(parse(event_type, json!({ "name": "n", "url": 3 })), removed("url"));
            assert_eq!(parse(event_type, json!("not an object")), removed("url"));
        }
        // MSC4411: a missing or non-string name removes an `m.widget`; a legacy widget does without.
        assert_eq!(parse("m.widget", json!({ "url": "https://x/" })), removed("name"));
        assert_eq!(parse("org.matrix.msc4411.widget", json!({ "name": 1, "url": "https://x/" })), removed("name"));
        assert!(parse("im.vector.modular.widgets", json!({ "url": "https://x/" })).is_ok());

        let other = parse("m.room.topic", json!({ "url": "https://x/" })).unwrap_err();
        assert_eq!(other.to_string(), "m.room.topic is not a widget state event type");
        assert_eq!(widget_event_types(), ["m.widget", "org.matrix.msc4411.widget", "im.vector.modular.widgets"]);
    }

    #[test]
    fn an_msc4411_widget_loads_its_url_as_checked() {
        for url in table("allowed").into_values() {
            let embed = new_widget(&url).embed(Some(WRAPPER), true).unwrap();
            assert_eq!(embed, WidgetEmbed { url: Url::parse(&url).unwrap().into(), uses_widget_api: true });
        }
        // Serialised: what the iframe loads is what the check parsed, not the event's string.
        for (url, loaded) in [
            ("  HTTPS://Example.org/", "https://example.org/"),
            ("ht\ttp://example.org/a b", "http://example.org/a%20b"),
            ("https://bücher.example/", "https://xn--bcher-kva.example/"),
            ("HTTP:\\\\example.org\\a", "http://example.org/a"),
            ("https://example.org/?room=$matrix_room_id", "https://example.org/?room=$matrix_room_id"),
        ] {
            assert_eq!(new_widget(url).embed(None, true).unwrap().url, loaded, "{url:?}");
        }
        let plain = parse("m.widget", json!({ "name": "n", "url": "https://x/" })).unwrap();
        assert!(!plain.embed(None, true).unwrap().uses_widget_api);
    }

    #[test]
    fn the_compat_wrapper_is_no_widget_of_either_kind() {
        let wrapper: Value = serde_json::from_str(include_str!("../tests/widget_urls.json")).unwrap();
        let wrapper = &wrapper["compat_wrapper"];
        let refused: BTreeMap<String, String> = serde_json::from_value(wrapper["refused"].clone()).unwrap();
        let wrapper = wrapper["wrapper"].as_str().unwrap();
        let expected =
            Err(WidgetEventError::Refused { reason: "a widget cannot load this client's compat wrapper".to_owned() });
        for (label, url) in refused {
            assert_eq!(new_widget(&url).embed(Some(wrapper), true), expected, "{label}");
            assert_eq!(legacy_widget(&url).embed(Some(wrapper), true), expected, "{label}");
        }
        // The attack: an MSC4411 widget that is this host's compat wrapper with a `javascript:` widget.
        let attack = "http://localhost:5173/widget_compatibility_wrapper/?legacy_widget_url=javascript:top.__pwned=1//";
        assert_eq!(new_widget(attack).embed(Some(WRAPPER), true), expected);
        // Other pages of the wrapper's origin are widgets as before.
        assert!(new_widget("http://localhost:5173/widgets/new/").embed(Some(WRAPPER), true).is_ok());
    }

    #[test]
    fn a_legacy_widget_loads_the_compat_wrapper() {
        for url in table("allowed").into_values() {
            let embed = legacy_widget(&url).embed(Some(WRAPPER), true).unwrap();
            assert!(embed.uses_widget_api);
            assert!(embed.url.starts_with(&format!("{WRAPPER}?legacy_widget_url=")), "{}", embed.url);
            assert_eq!(
                query(&embed.url),
                [
                    ("legacy_widget_url".to_owned(), url.clone()),
                    ("legacy_widget_id".to_owned(), "w".to_owned()),
                    ("legacy_wait_for_iframe_load".to_owned(), "true".to_owned()),
                ]
            );
        }
        let with_data = parse(
            "im.vector.modular.widgets",
            json!({ "url": "https://x/?t=$title", "waitForIframeLoad": false, "data": { "title": "Notes & more" } }),
        )
        .unwrap();
        let embed = with_data.embed(Some(WRAPPER), true).unwrap();
        assert_eq!(
            query(&embed.url)[2..],
            [
                ("legacy_wait_for_iframe_load".to_owned(), "false".to_owned()),
                ("legacy_widget_data".to_owned(), r#"{"title":"Notes & more"}"#.to_owned()),
            ]
        );
        // A wrapper URL with a query and a fragment keeps both; the widget goes into the query.
        let embed =
            legacy_widget("https://x/").embed(Some("https://wrapper.example/w?log_level=debug#f"), true).unwrap();
        assert!(embed
            .url
            .starts_with("https://wrapper.example/w?log_level=debug&legacy_widget_url=https%3A%2F%2Fx%2F&"));
        assert!(embed.url.ends_with("#f"));
        // The widget's parameters replace those of a wrapper URL that has them already (the wrapper
        // reads the first one); its other parameters stay.
        let planted = "https://wrapper.example/w?legacy_widget_url=javascript:x&log_level=debug&legacy_widget_id=evil\
                       &legacy_widget_data=%7B%7D&legacy_wait_for_iframe_load=false";
        let embed = legacy_widget("https://x/").embed(Some(planted), true).unwrap();
        assert_eq!(
            query(&embed.url),
            [
                ("log_level".to_owned(), "debug".to_owned()),
                ("legacy_widget_url".to_owned(), "https://x/".to_owned()),
                ("legacy_widget_id".to_owned(), "w".to_owned()),
                ("legacy_wait_for_iframe_load".to_owned(), "true".to_owned()),
            ]
        );
    }

    #[test]
    fn refused_urls_are_never_loaded() {
        for (label, url) in table("refused") {
            let new = new_widget(&url).embed(Some(WRAPPER), true).unwrap_err();
            let legacy = legacy_widget(&url).embed(Some(WRAPPER), true).unwrap_err();
            let expected = WidgetEventError::Refused { reason: widget_url_problem(&url, true).unwrap() };
            assert_eq!((&new, &legacy), (&expected, &expected), "{label}");
        }
        let refused = |reason: &str| -> Result<WidgetEmbed, WidgetEventError> {
            Err(WidgetEventError::Refused { reason: reason.to_owned() })
        };
        // `?wrapper=` can replace the compat wrapper by a link, so its URL is checked too.
        assert_eq!(
            legacy_widget("https://example.org/").embed(Some("javascript:top.__pwned=1//"), true),
            refused("compat wrapper: javascript: URLs are not allowed, only http: and https:")
        );
        assert_eq!(
            legacy_widget("https://example.org/").embed(None, true),
            refused("a legacy widget needs the compat wrapper")
        );
        // Without `allow_http`, the wrapper too must be https.
        assert_eq!(
            legacy_widget("https://example.org/").embed(Some(WRAPPER), false),
            refused("compat wrapper: http: URLs are not allowed, only https:")
        );
        assert_eq!(new_widget("http://x/").embed(None, false), refused("http: URLs are not allowed, only https:"));
    }
}
